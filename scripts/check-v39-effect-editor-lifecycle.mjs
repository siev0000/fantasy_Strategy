import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
import {chromium} from 'file:///C:/Users/skkt3/.codex/skills/develop-web-game/node_modules/playwright/index.mjs';

const out='output/web-game/effect-editor-lifecycle';mkdirSync(out,{recursive:true});
const browser=await chromium.launch();
try {
  for(const width of [390,1100]) {
    const page=await browser.newPage({viewport:{width,height:844}}),errors=[];
    page.on('pageerror',error=>errors.push(String(error.stack)));
    page.on('console',entry=>{if(entry.type()==='error')errors.push(entry.text());});
    await page.addInitScript(()=>{
      window.__previewClears=0;
      const clear=CanvasRenderingContext2D.prototype.clearRect;
      CanvasRenderingContext2D.prototype.clearRect=function(...args){
        if(this.canvas.closest('#v39-effect-preview-stage'))window.__previewClears++;
        return clear.apply(this,args);
      };
    });
    await page.goto(process.env.V39_TEST_URL||'http://127.0.0.1:3022',{waitUntil:'networkidle'});
    await page.locator('#v39-title-effect-settings-open').click();
    await page.waitForSelector('#v39-effect-idle-preview');
    await page.waitForTimeout(450);
    const idleClears=async()=>{
      await page.evaluate(()=>{window.__previewClears=0;});
      await page.waitForTimeout(450);
      return page.evaluate(()=>window.__previewClears);
    };
    const idle=await idleClears();assert.equal(idle,0,'idle editor must not run a preview render loop');
    assert.equal(await page.locator('#v39-effect-setting-preview-lower').count(),1);
    assert.equal(await page.locator('#v39-effect-setting-gradient-motion-mode').count(),1);
    await page.locator('#v39-effect-playback-mode').selectOption('loop');
    await page.waitForTimeout(200);
    assert.equal(await idleClears(),0,'selecting loop must not autoplay');
    await page.locator('#v39-effect-setting-preview-lower').click();
    assert.equal(await page.locator('#v39-effect-setting-preview-lower').getAttribute('aria-pressed'),'true');
    await page.waitForTimeout(250);
    assert((await idleClears())>0,'loop playback renders frames');
    await page.locator('#v39-effect-composite-selector').selectOption('thrust');
    await page.waitForTimeout(250);
    assert.equal(await page.locator('#v39-effect-setting-preview-lower').getAttribute('aria-pressed'),'true','selection preserves an explicitly running loop');
    assert((await idleClears())>0,'changed selection restarts through the same controller');
    await page.locator('#v39-effect-setting-preview-lower').click();
    assert.equal(await page.locator('#v39-effect-playback-mode').inputValue(),'loop','stop does not alter selected mode');
    assert.equal(await page.locator('#v39-effect-setting-preview-lower').getAttribute('aria-pressed'),'false');
    await page.waitForTimeout(200);
    assert.equal(await idleClears(),0,'stop cancels both playback and loop restart');
    await page.locator('#v39-effect-playback-mode').selectOption('once');
    await page.locator('#v39-effect-setting-preview-local').click();
    await page.waitForFunction(()=>document.getElementById('v39-effect-settings-status').textContent.includes('再生完了'));
    await page.waitForTimeout(250);
    assert.equal(await idleClears(),0,'one-shot settles without fixed-duration restore timer');
    await page.locator('#v39-effect-playback-mode').selectOption('frame');
    await page.waitForFunction(()=>Number(document.getElementById('v39-effect-frame-slider').max)>1);
    await page.locator('#v39-effect-frame-next').click();
    await page.waitForFunction(()=>document.getElementById('v39-effect-frame-slider').value==='1');
    await page.waitForTimeout(200);
    assert.equal(await idleClears(),0,'manual frame must not keep rendering');
    await page.locator('#v39-effect-playback-mode').selectOption('full-image');
    await page.locator('#v39-effect-setting-preview-lower').click();
    await page.waitForTimeout(200);
    assert.equal(await page.locator('#v39-effect-idle-preview').evaluate(canvas=>getComputedStyle(canvas).display),'block');
    assert.equal(await idleClears(),0,'full image is static');
    await page.screenshot({path:`${out}/full-image-${width}.png`});
    await page.locator('#v39-effect-composite-mode [data-mode="attribute"]').click();
    await page.locator('#v39-effect-composite-selector').selectOption('炎');
    await page.locator('[data-v39-effect-tab="color"]').click();
    await page.locator('#v39-effect-setting-color-mode').selectOption('gradient');
    await page.locator('[data-v39-effect-tab="motion"]').click();
    await page.locator('#v39-effect-setting-gradient-motion-mode').selectOption('fixed');
    assert(await page.locator('#v39-effect-setting-gradient-direction').isDisabled());
    await page.locator('#v39-effect-setting-gradient-motion-mode').selectOption('scroll');
    assert(!(await page.locator('#v39-effect-setting-gradient-direction').isDisabled()));
    await page.locator('#v39-effect-setting-gradient-direction').selectOption('right');
    const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('v39-effect-attribute-settings-v1')).settings['炎']);
    assert.equal(saved.gradientMotionMode,'scroll');assert.equal(saved.gradientDirection,'right');
    await page.locator('#v39-effect-playback-mode').selectOption('frame');
    await page.waitForFunction(()=>Number(document.getElementById('v39-effect-frame-slider').max)>2);
    await page.locator('#v39-effect-frame-slider').fill('2');
    await page.reload({waitUntil:'networkidle'});
    await page.waitForTimeout(900);
    assert.equal(await page.locator('#v39-effect-preview-stage canvas').count(),0,'saved frame mode must not initialize a hidden preview game');
    await page.locator('#v39-title-effect-settings-open').click();
    await page.waitForFunction(()=>document.getElementById('v39-effect-frame-slider').value==='2');
    assert.equal(await page.locator('#v39-effect-composite-selector').inputValue(),'炎','editor selection restores after initialization');
    assert.equal(await page.locator('#v39-effect-setting-gradient-motion-mode').inputValue(),'scroll');
    await page.waitForTimeout(250);
    assert.equal(await idleClears(),0,'restored manual frame is asleep');
    await page.locator('#v39-effect-settings-back').click();
    assert.equal(await page.locator('#v39-title-effect-settings-host').count(),0,'back restores title');
    await page.waitForTimeout(400);
    assert.equal(await idleClears(),0,'hidden preview stays asleep');
    await page.locator('#v39-title-effect-settings-open').click();
    assert.equal(await page.locator('#v39-effect-setting-preview-lower').count(),1,'reopen does not add controls');
    await page.waitForTimeout(200);
    await page.evaluate(()=>{window.__previewClears=0;});
    await page.locator('#v39-effect-frame-next').click();
    await page.waitForTimeout(150);
    assert((await page.evaluate(()=>window.__previewClears))>0,'reopened frame actually renders, not only its counter');
    await page.screenshot({path:`${out}/reopened-${width}.png`});
    await page.locator('#v39-effect-settings-back').click();
    await page.evaluate(()=>{window.closeV39PlayModeSelection();window.activateV39FooterTab('manage');window.openV39EffectSettings();});
    assert.equal(await page.locator('#v39-title-effect-settings-host').count(),0,'manage uses the same panel without a title host');
    await page.locator('#v39-effect-settings-back').click();
    assert.equal(await page.locator('#v39-effect-settings-panel').evaluate(panel=>panel.hidden),true);
    assert.equal(await page.locator('#v39-manage-menu').evaluate(menu=>menu.hidden),false);
    assert.deepEqual(errors,[]);
    writeFileSync(`${out}/result-${width}.json`,JSON.stringify({idleClears:idle,errors},null,2));
    console.log(`${width}: one owner, idle sleep, play/stop, once/loop/frame/full image, gradient, saved UI/frame, close/reopen passed`);
    await page.close();
  }
} finally {await browser.close();}
