import assert from 'node:assert/strict';
import {createServer} from 'vite';

const server=await createServer({configFile:false,root:'frontend',server:{middlewareMode:true},optimizeDeps:{noDiscovery:true,include:[]},appType:'custom'});
try{
  const {damageV39Ground,damageV39CaveEntrances,advanceV39GroundCollapses,clearV39Rubble,applyV39NaturalLandslide,damageV39EarthquakeGround}=await server.ssrLoadModule('/src/lib/v39-terrain-destruction.js');
  const {scheduleV39CaveEarthquake}=await server.ssrLoadModule('/src/lib/v39-cave-earthquake.js');
  const grid=Array.from({length:7},()=>Array(7).fill('平地'));
  grid[3][3]='丘陵';
  const heightLevelMap=Array.from({length:7},()=>Array(7).fill(1));
  heightLevelMap[3][3]=3;
  const map={w:7,h:7,grid,heightLevelMap,specialMap:Array.from({length:7},()=>Array(7).fill('')),terrainDamage:{}};
  const area=new Map([['3,3',1]]);
  const firstHit=damageV39Ground(map,area,1000,1);
  let first=firstHit.map;
  assert.deepEqual(firstHit.reports.map(report=>[report.power,report.damage]),[[1000,500]]);
  assert.equal(first.heightLevelMap[3][3],2);
  assert.equal(first.terrainDamage.cells['3,3'].collapseCount,1);
  assert.equal(first.terrainDamage.cells['3,3'].hp,500);
  assert.equal(Object.values(first.terrainDamage.pendingByTile).reduce((sum,event)=>sum+event.rubbleDurability,0),350);
  assert.deepEqual(Object.values(first.terrainDamage.pendingByTile).map(event=>event.power).sort((a,b)=>a-b),[80,120]);
  const villageState={neutralVillages:[{id:'village',x:3,y:2}]};
  const villageWarning=damageV39Ground(map,area,1000,1,villageState).map;
  const villageImpact=advanceV39GroundCollapses(villageWarning,2,villageState);
  assert(villageImpact.impacts.some(event=>event.x===3&&event.y===2));
  assert.equal(villageImpact.map.terrainDamage.rubbleByTile['3,2'],undefined);
  const mountain={...map,grid:map.grid.map((row,y)=>row.map((value,x)=>x===3&&y===3?'山岳':value))};
  const mountainCollapse=damageV39Ground(mountain,area,1500,1).map;
  assert.equal(Object.values(mountainCollapse.terrainDamage.pendingByTile).reduce((sum,event)=>sum+event.rubbleDurability,0),700);
  assert.deepEqual(Object.values(mountainCollapse.terrainDamage.pendingByTile).map(event=>event.power).sort((a,b)=>a-b),[100,140]);
  const oldSave={...map,heightLevelMap:map.heightLevelMap.map((row,y)=>row.map((value,x)=>x===3&&y===3?2:value)),terrainDamage:{cells:{'3,3':{hp:0,maxHp:500,terrain:'丘陵',broken:true}}}};
  const resumed=damageV39Ground(oldSave,area,450,1).map;
  assert.equal(resumed.terrainDamage.cells['3,3'].hp,250);
  assert.equal(resumed.terrainDamage.cells['3,3'].broken,false);
  first=advanceV39GroundCollapses(first,2).map;
  assert.equal(first.terrainDamage.rubbleByTile['3,3'].hp,219);
  const secondHit=damageV39Ground(first,area,1000,2);
  let second=secondHit.map;
  assert.deepEqual(secondHit.reports.map(report=>[report.power,report.damage]),[[1000,219],[1000,500]]);
  assert.equal(second.heightLevelMap[3][3],1);
  assert.equal(second.terrainDamage.cells['3,3'].collapseCount,2);
  assert.equal(second.terrainDamage.rubbleByTile['3,3'],undefined);
  second=advanceV39GroundCollapses(second,3).map;
  const third=damageV39Ground(second,area,1000,3).map;
  assert.equal(third.heightLevelMap[3][3],0);
  assert.equal(third.terrainDamage.cells['3,3'].collapseCount,3);
  assert.equal(third.terrainDamage.cells['3,3'].broken,true);
  const final=advanceV39GroundCollapses(third,4).map;
  const cleanup=damageV39Ground(final,area,1000,4).map;
  assert.equal(cleanup.terrainDamage.rubbleByTile['3,3'],undefined);
  assert.equal(cleanup.terrainDamage.cells['3,3'].collapseCount,3);
  const entranceMap={...map,grid:map.grid.map((row,y)=>row.map((value,x)=>x===2&&y===2?'洞窟':value)),terrainDamage:{}};
  const entranceArea=new Map([['2,2',1]]);
  const damagedEntrance=damageV39CaveEntrances(entranceMap,entranceArea,300).map;
  assert.equal(damagedEntrance.terrainDamage.cells['2,2'].entranceHp,200);
  const blockedEntrance=damageV39CaveEntrances(damagedEntrance,entranceArea,200).map;
  assert.equal(blockedEntrance.terrainDamage.rubbleByTile['2,2'].hp,350);
  const clearing=clearV39Rubble(blockedEntrance,{x:2,y:2,hp:100,ap:100,status:{攻撃:350}},{x:2,y:2});
  assert.equal(clearing.ok,true);
  assert.equal(clearing.map.terrainDamage.rubbleByTile['2,2'],undefined);
  const naturalMap={...map,terrainDamage:{}};
  const natural=applyV39NaturalLandslide(naturalMap,{disasterId:'災害:土砂崩れ',x:3,y:3,tileKeys:['3,3']});
  assert.equal(natural.tileKeys.length,2);
  assert.equal(Object.values(naturalMap.terrainDamage.rubbleByTile).reduce((sum,row)=>sum+row.hp,0),350);
  assert.deepEqual(Object.keys(naturalMap.terrainDamage.rubbleByTile).sort(),[...natural.tileKeys].sort());
  const villageMap={...map,terrainDamage:{}};
  const villageNatural=applyV39NaturalLandslide(villageMap,{disasterId:'災害:土砂崩れ',x:3,y:3},{neutralVillages:[{x:3,y:2}]});
  assert(villageNatural.tileKeys.includes('3,2'));
  assert.equal(villageMap.terrainDamage.rubbleByTile['3,2'],undefined);
  const caveMap={...map,isUnderground:true,grid:grid.map(row=>row.map(()=>'洞窟')),
    entrances:[{x:1,y:1,surfaceEntrance:{x:3,y:3}}],terrainDamage:{}};
  const worlds={'cave:entrance-3-3:1':{map:caveMap}};
  const outside=scheduleV39CaveEarthquake(worlds,[{id:'quake-outside',tileKeys:['5,5']}],2);
  assert.equal(outside.scheduled.length,0);
  const quake=scheduleV39CaveEarthquake(worlds,[{id:'quake-inside',tileKeys:['3,3']}],2);
  assert(quake.scheduled.length>=1&&quake.scheduled.length<=3);
  const quakeMap=quake.worlds['cave:entrance-3-3:1'].map;
  assert(quake.scheduled.every(row=>row.x!==1||row.y!==1));
  assert(Object.values(quakeMap.terrainDamage.pendingByTile).every(row=>row.resolvesAtTurn===3&&row.power===80&&row.hiddenWarning===true));
  const resolvedQuake=advanceV39GroundCollapses(quakeMap,3);
  assert.equal(resolvedQuake.impacts.length,quake.scheduled.length);
  const quakeGround=damageV39EarthquakeGround(map,{disasterId:'災害:地震',tileKeys:['3,3'],damagePower:80},5);
  assert.equal(quakeGround.map.terrainDamage.cells['3,3'].hp,420);
  assert.equal(quakeGround.map.heightLevelMap[3][3],3);
  const nearCollapse={...map,terrainDamage:{cells:{'3,3':{hp:80,maxHp:500,terrain:'丘陵',broken:false}}}};
  const quakeCollapse=damageV39EarthquakeGround(nearCollapse,{disasterId:'災害:地震',tileKeys:['3,3'],damagePower:80},5);
  assert.equal(quakeCollapse.map.heightLevelMap[3][3],2);
  assert(Object.values(quakeCollapse.map.terrainDamage.pendingByTile).every(row=>row.resolvesAtTurn===6));
  console.log('PASS: repeated collapse, downhill power, distributed debris, dual damage, height zero limit');
}finally{await server.close();}
