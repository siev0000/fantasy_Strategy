import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
import {chromium} from 'file:///C:/Users/skkt3/.codex/skills/develop-web-game/node_modules/playwright/index.mjs';

const output='output/web-game/trade-input-stability';mkdirSync(output,{recursive:true});
const browser=await chromium.launch();
try{for(const width of [320,390,1100]){
  const page=await browser.newPage({viewport:{width,height:844}}),errors=[];
  page.on('pageerror',error=>errors.push(String(error.stack)));
  page.on('dialog',dialog=>dialog.accept());
  await page.goto(process.env.V39_TEST_URL||'http://127.0.0.1:3022',{waitUntil:'networkidle'});
  await page.locator('[data-v39-test-tools]').click();
  await page.locator('[data-test-action="trade-test-start"]').click();
  await page.waitForFunction(()=>!window.isV39MapInputLocked?.());
  const amount=page.locator('[data-trade-basket="0"] input[type="number"]');
  await amount.fill('31');await amount.dispatchEvent('change');
  await amount.evaluate(input=>{window.__tradeAmount=input;window.__tradeFooter=document.querySelector('[data-trade-action="propose"]');});
  await page.locator('[data-trade-fold="delivery"] > summary').click();
  const grace=page.locator('[data-trade-field="grace"]');
  await grace.fill('4');await grace.dispatchEvent('change');
  assert(await amount.evaluate(input=>input===window.__tradeAmount),'schedule edits retain quantity node');
  assert(await page.evaluate(()=>window.__tradeFooter===document.querySelector('[data-trade-action="propose"]')),'proposal button retained');
  await grace.fill('');
  await page.evaluate(()=>{
    window.__tradeGrace=document.activeElement;
    const body=document.querySelector('.v39-trade-body');body.scrollTop=30;window.__tradeScroll=body.scrollTop;
    for(let i=0;i<10;i++)window.dispatchEvent(new CustomEvent('v39:game-state-changed'));
  });
  await page.waitForTimeout(120);
  assert.equal(await grace.inputValue(),'','in-progress number survives background updates');
  assert(await grace.evaluate(input=>input===window.__tradeGrace&&document.activeElement===input),'focus and input node retained');
  assert(await page.evaluate(()=>document.querySelector('.v39-trade-body').scrollTop===window.__tradeScroll),'scroll retained');
  await page.evaluate(()=>{const s=window.getV39GameState(),players=structuredClone(s.players);players.find(row=>row.id===s.activePlayerId).label='更新後の勢力';window.setV39GameState({players},{reason:'trade-label-test'});});
  await page.waitForTimeout(100);
  assert.equal(await grace.inputValue(),'','unfinished number survives changed markup');
  await grace.fill('5');await grace.dispatchEvent('change');
  assert.equal(await grace.inputValue(),'5','schedule edit committed');
  await page.locator('[data-trade-fold="delivery"] > summary').click();
  await page.locator('[data-trade-add-side="0"]').click();
  const search=page.locator('[data-trade-resource-search]');
  await search.fill('木');
  await search.evaluate(input=>{window.__tradeSearch=input;input.setSelectionRange(0,1);window.__tradePicker=document.querySelector('.v39-trade-picker-backdrop');});
  await page.evaluate(()=>window.dispatchEvent(new CustomEvent('v39:game-state-changed')));
  await page.waitForTimeout(100);
  assert(await search.evaluate(input=>input===window.__tradeSearch&&document.activeElement===input&&input.selectionStart===0&&input.selectionEnd===1),'search node focus and selection retained');
  assert(await page.evaluate(()=>window.__tradePicker===document.querySelector('.v39-trade-picker-backdrop')),'picker overlay retained');
  await page.locator('[data-trade-resource-add="木材"]').click();
  assert(await search.evaluate(input=>input===window.__tradeSearch),'adding goods retains search input');
  await search.fill('');await page.locator('[data-trade-resource-filter="basic"]').click();
  await page.locator('[data-trade-resource-add="鉄"]').evaluate(button=>window.__tradeIron=button);
  const titleBefore=await page.locator('[data-trade-resource-add="鉄"]').getAttribute('title');
  await page.evaluate(()=>{
    const s=window.getV39GameState(),players=structuredClone(s.players),own=players.find(row=>row.id===s.activePlayerId);
    own.factionState.settlements[0].materialStockByType.鉄+=7;
    window.setV39GameState({players},{reason:'trade-stability-stock-test'});
  });
  await page.waitForTimeout(150);
  assert.notEqual(await page.locator('[data-trade-resource-add="鉄"]').getAttribute('title'),titleBefore,'stock updates even with focus inside modal');
  assert(await page.locator('[data-trade-resource-add="鉄"]').evaluate(button=>button===window.__tradeIron),'changed stock retains resource button');
  await page.locator('[data-trade-picker-close]').last().click();
  await page.locator('[data-trade-basket="0"] [data-trade-item-select="木材"]').click();
  const wood=page.locator('[data-trade-basket="0"] input[type="number"]');
  await wood.fill('8');await wood.dispatchEvent('change');
  await wood.evaluate(input=>window.__tradeWood=input);
  await page.locator('[data-trade-basket="1"] [data-trade-item-select]').first().click();
  assert(await wood.evaluate(input=>input===window.__tradeWood),'opposite side selection retains input');
  await page.locator('[data-trade-fold="delivery"] > summary').click();
  assert.equal(await grace.inputValue(),'5','schedule kept after resource edits');
  await page.screenshot({path:`${output}/proposal-${width}.png`});
  await page.locator('[data-trade-action="propose"]').click();
  const books=await page.evaluate(()=>window.getV39TradeRules().listV39Trades(window.getV39GameState()));
  assert.equal(books[0].sides[0].goods.木材,8);assert.equal(books[0].grace,5);
  await page.evaluate(()=>{const s=window.getV39GameState(),players=structuredClone(s.players);for(const player of players)for(const book of player.factionState.tradeContracts||[]){book.status='interrupted';book.reason='再日程試験';}window.setV39GameState({players},{reason:'trade-contract-refresh'});});
  const date=page.locator('input[id^="trade-date-"]');await date.waitFor();
  await page.locator('[data-trade-contract] details > summary').first().click();
  await date.fill('99');await date.evaluate(input=>window.__tradeDate=input);
  await page.locator('[data-trade-tab="contracts"]').focus();
  await page.evaluate(()=>{const s=window.getV39GameState(),players=structuredClone(s.players);for(const player of players)for(const book of player.factionState.tradeContracts||[])book.reason='状態を更新';window.setV39GameState({players},{reason:'trade-contract-refresh'});});
  await page.waitForTimeout(100);
  assert.equal(await date.inputValue(),'99','unsubmitted restart date survives status update after blur');
  assert(await date.evaluate(input=>input===window.__tradeDate),'contract date node retained');
  assert(await page.locator('[data-trade-contract] details').first().evaluate(node=>node.open),'contract details stay open');
  await page.evaluate(()=>{const s=window.getV39GameState(),peer=s.players.find(player=>player.id!==s.activePlayerId);window.setV39GameState({activePlayerId:peer.id,timeline:{...s.timeline,activeTurnPlayerId:peer.id}},{reason:'trade-owner-test'});});
  await page.waitForTimeout(100);assert(await page.locator('#v39-trade-modal').isHidden(),'player change closes stale owner draft');
  assert.deepEqual(errors,[]);
  console.log(`${width}: retained quantity, schedule, footer, picker, search selection, live stock and committed proposal passed`);
  await page.close();
}}finally{await browser.close();}
