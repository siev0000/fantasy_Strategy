import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { chromium } from "file:///C:/Users/skkt3/.codex/skills/develop-web-game/node_modules/playwright/index.mjs";

const directory="output/web-game/cave-rewards-logs";
mkdirSync(directory,{recursive:true});
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
page.on("pageerror",error=>errors.push(error.stack||String(error)));
try{
  await page.goto("http://127.0.0.1:3022",{waitUntil:"networkidle"});
  await page.locator("[data-v39-cave-test]").click();
  await page.getByRole("button",{name:"探索ゲーム",exact:true}).click();
  await page.getByRole("button",{name:"探索開始",exact:true}).click();
  await page.waitForTimeout(800);
  const report=await page.evaluate(async()=>{
    const check=(value,message)=>{if(!value)throw new Error(message);};
    const exp=await import("/src/lib/v39-unit-experience.js");
    const {getHexNeighborCoords}=await import("/src/lib/hex-grid.js");
    const initial=window.getV39ActiveFactionState(),actor=window.getV39SelectedSquadUnit();
    const worldId=window.getV39GameState().activeWorldId;
    const reward=exp.resolveV39CombatExpReward({targetLevel:7,targetCategory:"human"});
    check(reward.rawExp===exp.resolveV39UnitExpNeed(7,"human"),"same-level EXP equals next-level requirement");
    const units=[{...actor,id:"a",worldId,hp:100,level:7,exp:0,totalExp:exp.resolveV39UnitTotalExpForLevel(7,exp.resolveV39UnitRaceCategory(actor))},{...actor,id:"b",worldId,hp:100},{...actor,id:"dead",worldId,hp:0},{...actor,id:"surface",worldId:"surface",hp:100}];
    const faction={units,squads:[{id:"party",unitIds:units.map(unit=>unit.id)}]};
    const distributed=exp.distributeV39CombatExperience(faction,"a",reward.rawExp);
    check(distributed.awards.length===2&&distributed.awards.every(row=>row.amount===reward.rawExp),"full party reward; exclude dead/off-world");
    const partial=exp.distributeV39CombatExperience(faction,"a",.4);
    check(partial.factionState.combatExpRemainder===.4,"fractional EXP retained");
    check(exp.resolveV39DamageExpReward({level:7,maxHp:100,expRewardedHpDamage:100},100,0).rawExp===0,"healing farming cap");
    const map=window.__v39FieldRuntime.mapData,site=map.caveSites.find(row=>row.wall);
    check(!!site,"mineral deposit exists");
    const floor=getHexNeighborCoords(map.w,map.h,site.x,site.y).find(tile=>map.grid[tile.y][tile.x]!=="岩壁");
    site.discovered=true;site.remaining=3;
    window.updateV39ActiveFactionState({units:initial.units.map(unit=>unit.id===actor.id?{...unit,x:floor.x,y:floor.y,ap:100,currentAp:100,waitTurnNumber:0}:unit)});
    window.dispatchEvent(new CustomEvent("v39:squad-detail-rendered"));
    window.dispatchEvent(new CustomEvent("v39:tile-selected",{detail:{x:site.x,y:site.y}})); const button=document.getElementById("mobileBattleGatherUse");
    check(button&&!button.disabled,"adjacent deposit in native actions");button.click();
    const after=window.getV39ActiveFactionState(),mined=after.units.find(unit=>unit.id===actor.id);
    check(mined.ap===70,"mining consumes 30 AP");
    check(map.caveSites.find(row=>row.id===site.id).remaining===2,"deposit decreased");
    const squad=after.squads.find(row=>row.unitIds.includes(actor.id));
    const cargo=squad.cargoByUnitId?.[actor.id]||squad.cargo;
    check(cargo?.resourcesByType?.[site.name]>=1,"resource actually acquired in cargo");
    check(after.activityLog.some(row=>row.category==="採取"),"mining saved in activity log");
    window.updateV39ActiveFactionState({units:after.units.map(unit=>unit.id===actor.id?{...unit,ap:29,currentAp:29}:unit)});
    window.dispatchEvent(new CustomEvent("v39:squad-detail-rendered"));
    check(document.getElementById("mobileBattleGatherUse").disabled,"insufficient AP disabled");
    const gem=map.caveSites.find(row=>row.name==="宝石");
    gem.discovered=true;gem.remaining=1;
    const gemFloor=getHexNeighborCoords(map.w,map.h,gem.x,gem.y).find(tile=>map.grid[tile.y][tile.x]!=="岩壁");
    window.updateV39ActiveFactionState({units:after.units.map(unit=>unit.id===actor.id?{...unit,x:gemFloor.x,y:gemFloor.y,ap:100,currentAp:100,waitTurnNumber:window.getV39GameState().timeline.turnNumber}:unit)});
    window.dispatchEvent(new CustomEvent("v39:squad-detail-rendered"));
    check(document.getElementById("mobileBattleGatherUse").disabled,"waiting cannot mine");
    window.updateV39ActiveFactionState({units:window.getV39ActiveFactionState().units.map(unit=>unit.id===actor.id?{...unit,waitTurnNumber:0}:unit)});
    window.dispatchEvent(new CustomEvent("v39:squad-detail-rendered"));
    window.dispatchEvent(new CustomEvent("v39:tile-selected",{detail:{x:gem.x,y:gem.y}})); document.getElementById("mobileBattleGatherUse").click();
    const gemSquad=window.getV39ActiveFactionState().squads.find(row=>row.unitIds.includes(actor.id));
    check((gemSquad.cargoByUnitId?.[actor.id]||gemSquad.cargo).resourcesByType.宝石===1,"gem acquired");
    check(map.caveSites.find(row=>row.id===gem.id).remaining===0,"gem exhausted");
    check(document.getElementById("mobileBattleGatherUse").disabled,"exhausted deposit disabled");
    const saved=window.captureV39ExplorationWorlds();
    check(saved[worldId].map.caveSites.find(row=>row.id===gem.id).remaining===0,"mined remainder captured for save");
    window.dispatchEvent(new CustomEvent("v39:combat-log",{detail:{summary:"ログ試験 / 合計12 (5,7)",attackerId:actor.id,entries:[]}}));
    check(window.getV39SideRailMessages().some(row=>row.channel==="battle"&&row.message.includes("ログ試験")),"combat channel records cave battle");
    check(window.getV39ActiveFactionState().activityLog.some(row=>row.category==="戦闘"&&row.message.includes("ログ試験")),"combat persists in activity log");
    const preview=document.getElementById("v39-chat-preview");
    check(document.getElementById("v39-battle-preview").classList.contains("show")&&document.getElementById("v39-battle-preview").textContent.includes("ログ試験"),"combat popup visible");
    document.querySelector(".v39-side-log-collapse").click();
    window.pushV39ChatMessage("<b>新着チャット</b>",{title:"参加者"});
    check(preview.textContent.includes("<b>新着チャット</b>")&&!preview.querySelector("b"),"collapsed chat popup escaped");
    for(let i=0;i<5;i++)window.pushV39ChatMessage(`新着${i}`);
    check(preview.children.length===3,"bounded popup stack");
    preview.querySelector("button").click();
    check(document.getElementById("v39-side-log").dataset.channel==="chat"&&!document.getElementById("v39-side-log").classList.contains("collapsed"),"popup opens channel");
    check(!preview.classList.contains("show"),"opened chat clears its previews");
    window.pushV39ChatMessage("既読画面");check(!preview.classList.contains("show"),"open chat does not popup");
    window.dispatchEvent(new CustomEvent("v39:combat-log",{detail:{summary:"戦闘表示確認",attackerId:actor.id,entries:[]}}));
    return {reward:reward.rawExp,awards:distributed.awards.map(row=>row.amount),cargo,remaining:map.caveSites.find(row=>row.id===site.id).remaining};
  });
  report.nativeCombat=await page.evaluate(async()=>{
    const {getHexNeighborCoords}=await import("/src/lib/hex-grid.js");
    const state=window.getV39GameState(),map=window.__v39FieldRuntime.mapData,faction=window.getV39ActiveFactionState(),actor=window.getV39SelectedSquadUnit();
    const enemy=state.enemies.find(row=>row.hp>0);
    const adjacent=getHexNeighborCoords(map.w,map.h,enemy.x,enemy.y).find(tile=>map.grid[tile.y][tile.x]!=="岩壁");
    window.updateV39ActiveFactionState({units:faction.units.map(unit=>unit.id===actor.id?{...unit,x:adjacent.x,y:adjacent.y,ap:100,currentAp:100,status:{...unit.status,命中:99999}}:unit)});
    const before=window.getV39ActiveFactionState().units.map(unit=>({id:unit.id,totalExp:unit.totalExp}));
    // 命中を安定させつつPhaserのランダムなテクスチャIDの一意性を残す。
    const random=Math.random;Math.random=()=>random()*.5;
    try{
      const ok=window.executeV39FactionCombatAction({playerId:state.activePlayerId,attackerId:actor.id,targetUnitId:enemy.id,skillRow:{名前:"採取後戦闘試験",行動:"A",全威力:100000,判定:"攻撃",攻撃手段:"素手",射程:10,AP消費:10}});
      if(!ok)throw new Error("native combat rejected");
    }finally{Math.random=random;}
    const after=window.getV39ActiveFactionState();
    if(!after.units.every(unit=>unit.totalExp>(before.find(row=>row.id===unit.id).totalExp||0)))throw new Error(`native combat did not grant party EXP ${JSON.stringify({before,after:after.units.map(unit=>({id:unit.id,totalExp:unit.totalExp,hp:unit.hp})),log:window.getV39SideRailMessages().at(-1)})}`);
    if(!window.getV39SideRailMessages().some(row=>row.channel==="battle"&&row.message.includes("採取後戦闘試験")))throw new Error("real combat missing from rail");
    const entry=window.getV39SideRailMessages().filter(row=>row.channel==="battle"&&row.message.includes("採取後戦闘試験")).at(-1);
    if(!entry.message.includes(`${actor.name} / 採取後戦闘試験`)||!entry.message.includes(enemy.name)||!entry.message.includes("ダメージ"))throw new Error("real combat attacker/skill/target/damage missing");
    return after.units.map(unit=>({id:unit.id,level:unit.level,totalExp:unit.totalExp}));
  });
  await page.waitForTimeout(2000);
  await page.screenshot({path:`${directory}/desktop.png`});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(100);
  assert.equal(await page.locator("#v39-battle-preview").evaluate(el=>{const rect=el.getBoundingClientRect();return rect.width>0&&rect.left>=0&&rect.right<=innerWidth;}),true);
  await page.screenshot({path:`${directory}/mobile.png`});
  await page.waitForTimeout(4200);
  assert.equal(await page.locator("#v39-battle-preview").evaluate(el=>el.classList.contains("show")),false);
  assert.deepEqual(errors,[]);
  writeFileSync(`${directory}/report.json`,JSON.stringify({report,errors},null,2));
  console.log("PASS cave rewards, adjacent mining, combat/chat logs, popup bounds and expiry",report);
}finally{await browser.close();}
