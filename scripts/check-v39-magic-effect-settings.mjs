import assert from 'node:assert/strict';
import {build} from 'esbuild';
const data=new Map();
globalThis.window={localStorage:{getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v)},dispatchEvent(){}};
const bundle=await build({stdin:{contents:`
export * from './frontend/src/lib/v39-effect-settings.js';
export {resolveV39CombatEffect} from './frontend/src/lib/v39-combat-effect-rules.js';
`,resolveDir:process.cwd()},bundle:true,write:false,format:'esm',platform:'node'});
const url='data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64');
const m=await import(url);
m.setV39EffectSettingsCatalog(['斬撃','爆裂','落雷']);
const row={名前:'火球',攻撃手段:'魔法',アニメ:'斬撃'};
assert.equal(m.resolveV39CombatEffect(row).effectName,'斬撃');
m.saveV39MagicEffectSetting('火球',{baseEffect:'爆裂',gradientEnabled:true,gradientColorA:'#FF0000',scaleMultiplierPercent:120,playbackSpeedPercent:150});
assert.equal(m.resolveV39CombatEffect(row).effectName,'爆裂');
assert.equal(m.resolveV39CombatEffect(row).settings.playbackSpeedPercent,150);
assert.equal(m.resolveV39CombatEffect({...row,名前:'別の魔法'}).effectName,'斬撃');
assert.equal(m.resolveV39CombatEffect({...row,攻撃手段:'剣'}).effectName,'斬撃');
const snapshot=m.getV39MagicEffectSettingsSnapshot();
assert.throws(()=>m.prepareV39MagicEffectImport({火球:null},['火球']));
assert.equal(m.getV39MagicEffectSetting('火球').baseEffect,'爆裂');
m.resetV39MagicEffectSetting('火球');
assert.equal(m.resolveV39CombatEffect(row).effectName,'斬撃');
const prepared=m.prepareV39MagicEffectImport({...snapshot,未知:{baseEffect:'落雷'}},['火球']);
assert.equal(prepared.skippedCount,1);
m.applyV39MagicEffectImport(prepared);
assert.equal(m.resolveV39CombatEffect(row).effectName,'爆裂');
const reloaded=await import(url+'#reload');
reloaded.setV39EffectSettingsCatalog(['斬撃','爆裂','落雷']);
assert.equal(reloaded.getV39MagicEffectSetting('火球').baseEffect,'爆裂');
console.log('Magic effect isolation, persistence, reset, import and fallback OK');
