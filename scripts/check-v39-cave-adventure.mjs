import assert from "node:assert/strict";
import { chromium } from "file:///C:/Users/skkt3/.codex/skills/develop-web-game/node_modules/playwright/index.mjs";
import { mkdirSync, writeFileSync } from "node:fs";

mkdirSync("output/web-game/cave-adventure",{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];
page.on("pageerror",error=>errors.push(String(error)));
try {
  await page.goto("http://127.0.0.1:3022",{waitUntil:"networkidle"});
  const report=await page.evaluate(async()=>{
    const c=await import("/src/lib/v39-cave-adventure.js");
    const paths=await import("/src/lib/v39-cave-generator.js");
    const combat=await import("/src/lib/v39-combat-engine.js");
    const checks=[];
    function check(name,condition){if(!condition)throw new Error(name);checks.push(name);}
    function rejects(work){try{work();return false;}catch{return true;}}
    const fresh=()=>c.createCaveAdventure(c.defaultCaveProfiles(),{seed:"regression",templateId:"passage"});
    const game=fresh();
    check("three derived characters",game.party.length===3&&game.party.every(u=>u.hp>0&&u.derivedCharacter.ok&&u.ap===100));
    check("requires three",rejects(()=>c.createCaveAdventure(c.defaultCaveProfiles().slice(0,2))));
    const following=fresh();following.enemies=[];
    const followPath=paths.findV39CavePath(following.map,following.position,following.map.entrances[1]);
    c.moveCaveParty(following,followPath[3]);
    check("followers use traversed path",c.cavePartyFormation(following).every((member,index)=>member.position.key===followPath[3-index].key));
    const order=following.party.map(unit=>unit.id),data=new Map(following.party.map(unit=>[unit.id,JSON.stringify(unit)]));
    c.reorderCaveParty(following,order[2],-1);
    c.reorderCaveParty(following,order[2],-1);
    check("reorder preserves characters",following.party[0].id===order[2]&&following.party.every(unit=>JSON.stringify(unit)===data.get(unit.id)));
    check("formation follows new order",c.cavePartyFormation(following)[0].unit.id===order[2]);
    check("reorder boundaries",rejects(()=>c.reorderCaveParty(following,order[2],-1))&&rejects(()=>c.reorderCaveParty(following,"missing",1)));
    following.position={...following.map.entrances[1]};c.descendCave(following);
    check("floor keeps order resets trail",following.party[0].id===order[2]&&following.trail.every(tile=>tile.key===following.position.key));
    const path=paths.findV39CavePath(game.map,game.position,game.map.entrances[1]);
    game.enemies=[];
    c.moveCaveParty(game,path[1]);
    check("shared move AP",game.party.every(u=>u.ap===80&&u.x===game.position.x&&u.y===game.position.y));
    check("walls blocked",rejects(()=>c.moveCaveParty(game,{x:0,y:0})));
    game.party[0].ap=0;
    check("AP blocks movement",rejects(()=>c.moveCaveParty(game,path[2])));
    c.endCaveTurn(game,()=>0);
    check("turn restores AP",game.turn===2&&game.party.every(u=>u.ap===100));
    const actor=game.party[0];actor.hp-=20;
    c.changeCaveEquipment(game,actor.id,"武器1","");
    check("unequip no healing",game.party[0].hp<=actor.hp&&!game.party[0].equipment.some(e=>e.slot==="武器1"));
    const weapon=c.caveEquipmentOptions.find(row=>row.装備名==="長剣");
    c.changeCaveEquipment(game,actor.id,"武器1",weapon.装備名);
    check("equip derived",game.party[0].equipment.some(e=>e.slot==="武器1"&&e.name==="長剣")&&game.party[0].derivedCharacter.ok);
    check("no early stairs",rejects(()=>c.descendCave(game)));
    game.position={...game.map.entrances[1]};
    const savedHp=game.party.map(u=>u.hp),savedGear=JSON.stringify(game.party.map(u=>u.equipment)),oldSeed=game.map.seed;
    c.descendCave(game);
    check("stairs preserve HP equipment",game.floor===2&&game.map.seed!==oldSeed&&JSON.stringify(game.party.map(u=>u.hp))===JSON.stringify(savedHp)&&JSON.stringify(game.party.map(u=>u.equipment))===savedGear);
    const fight=fresh(),enemy=fight.enemies[0];
    const adjacent=paths.findV39CavePath(fight.map,enemy,fight.position)[1];
    fight.position={...adjacent};fight.enemies=[enemy];c.revealCave(fight);
    enemy.hp=enemy.maxHp=10000;enemy.status.防御=0;enemy.status.回避=0;
    const row=c.caveActions(fight.party[0])[0],cost=combat.resolveAttackApCost(row,fight.party[0]);
    fight.party[0].ap=cost-1;
    check("attack requires AP",rejects(()=>c.useCaveAction(fight,fight.party[0].id,0,enemy.id,()=>0))&&enemy.hp===10000);
    fight.party[0].ap=100;
    const expected=combat.computeAttackDamage({attacker:fight.party[0],target:enemy,skillRow:row,random:()=>0}).total;
    c.useCaveAction(fight,fight.party[0].id,0,enemy.id,()=>0);
    check("shared damage formula AP",enemy.hp===10000-expected&&expected>0&&fight.party[0].ap===100-cost);
    check("experience finite",fight.party.every(u=>Number.isFinite(u.totalExp))&&enemy.expRewardedHpDamage===expected);
    const hp=fight.party.reduce((sum,u)=>sum+u.hp,0);
    enemy.provoked=true;enemy.status.命中=10000;
    c.endCaveTurn(fight,()=>0);
    check("enemy attacks",fight.party.reduce((sum,u)=>sum+u.hp,0)<hp);
    const healer=fresh();healer.enemies=[];
    const healIndex=c.caveActions(healer.party[2]).findIndex(r=>combat.resolveSkillHealing(r,healer.party[2])>0);
    check("healing available",healIndex>=0);
    healer.party[0].hp-=30;const before=healer.party[0].hp;
    c.useCaveAction(healer,healer.party[2].id,healIndex,healer.party[0].id,()=>0);
    check("heals living ally",healer.party[0].hp>before&&healer.party[0].hp<=healer.party[0].maxHp);
    healer.party[0].hp=-5;
    check("cannot heal corpse",rejects(()=>c.useCaveAction(healer,healer.party[2].id,healIndex,healer.party[0].id,()=>0)));
    for(const unit of healer.party)unit.hp=-1;
    c.endCaveTurn(healer,()=>0);
    check("defeat no revival",healer.phase==="defeat"&&healer.party.every(u=>u.hp===-1&&u.ap===0));
    return {checks};
  });
  assert.deepEqual(errors,[]);
  writeFileSync("output/web-game/cave-adventure/report.json",JSON.stringify({report,errors,uiTest:"scripts/check-v39-cave-native.mjs"},null,2));
  console.log(JSON.stringify({checks:report.checks.length,errors}));
} finally {await browser.close();}
