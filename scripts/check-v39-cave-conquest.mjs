import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const url=source=>`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`;
const balance=url(readFileSync("frontend/src/lib/v39-gameplay-balance.js","utf8"));
const nest=url(readFileSync("frontend/src/lib/v39-cave-nest-rules.js","utf8").replace('"./v39-gameplay-balance.js"',JSON.stringify(balance)));
const source=readFileSync("frontend/src/lib/v39-cave-conquest-rules.js","utf8").replace('"./v39-gameplay-balance.js"',JSON.stringify(balance))
  .replace('"./v39-cave-nest-rules.js"',JSON.stringify(nest));
const {updateV39CaveConquest:update,advanceV39CaveRecolonization:advance}=await import(url(source));
const map={isUnderground:true,caveBossIds:["boss"],caveBossRace:"ビートル"};
assert.equal(update({...map,isUnderground:false},[],1),null);
assert.equal(update({...map,caveMine:{}},[],1),null);
assert.equal(update(map,[{id:"boss",hp:1}],1).bossDefeated,undefined);
let conquest=update(map,[{id:"boss",hp:0,race:"ビートル"}],1);
assert.equal(conquest.bossDefeated,true);assert.equal(conquest.previousRace,"ビートル");
const plan={settlerCount:2,requiresFood:true,foodAmount:20};
for(let turn=2;turn<=4;turn++)conquest=advance(conquest,turn,{playerPresent:false,plan,hasEnemies:false});
assert.equal(conquest.progressTurns,3);
conquest=advance(conquest,5,{playerPresent:true,plan,hasEnemies:false});
conquest=advance(conquest,6,{playerPresent:true,plan,hasEnemies:false});
assert.equal(conquest.progressTurns,1);
assert.deepEqual(advance(conquest,6,{playerPresent:false,plan,hasEnemies:false}),conquest);
conquest=advance(conquest,7,{playerPresent:false,plan:{...plan,foodAmount:0},hasEnemies:false});
assert.equal(conquest.progressTurns,1);
conquest=advance(conquest,8,{playerPresent:false,plan:{...plan,settlerCount:1},hasEnemies:false});
assert.equal(conquest.progressTurns,1);
conquest=advance(conquest,9,{playerPresent:false,plan,hasEnemies:true});
assert.equal(conquest.progressTurns,1);
for(let turn=10;turn<=13;turn++)conquest=advance(JSON.parse(JSON.stringify(conquest)),turn,{playerPresent:false,plan,hasEnemies:false});
assert.equal(conquest.ready,true);assert.equal(conquest.progressTurns,5);
assert.equal(update({...map,caveConquest:conquest},[],20),conquest);
assert.equal(advance(conquest,14,{playerPresent:true,plan,hasEnemies:false}).progressTurns,4);
console.log("cave conquest: boss tracking, deferred/save, five-turn recolonization, visit rollback, same-turn deduplication and food/member/enemy gates passed");
