import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const moduleUrl = source => `data:text/javascript;base64,${Buffer.from(source).toString("base64")}`;
const balanceUrl = moduleUrl(readFileSync("frontend/src/lib/v39-gameplay-balance.js", "utf8"));
const { V39_CAVE_MINE_BALANCE:rules } = await import(balanceUrl);
const source = readFileSync("frontend/src/lib/v39-cave-mine-rules.js", "utf8").replace('"./v39-gameplay-balance.js"', JSON.stringify(balanceUrl));
const { inspectV39CaveMine:inspect, createV39CaveMine:create, advanceV39CaveMine:advance } = await import(moduleUrl(source));
const map = { isUnderground:true, caveBossIds:["boss"], caveSites:[{kind:"ore",remaining:0},{kind:"ore"},{kind:"gem"}] };
assert.equal(inspect(map,[{id:"boss",hp:1}]).eligible,false);
assert.equal(inspect(map,[{id:"boss",hp:0},{id:"wolf",hp:1}]).eligible,false);
assert.equal(inspect({...map,isUnderground:false},[]).eligible,false);
assert.equal(inspect({...map,caveBossIds:[]},[]).eligible,false);
assert.equal(inspect({...map,caveSites:[]},[]).eligible,false);
let mine = create(map,[],"p1",1);
assert.deepEqual(mine.resourcesPerCycle,{鉱石:1,宝石:1});
assert.equal(inspect({...map,caveMine:mine},[]).eligible,false);
assert.throws(()=>create(map,[],"",1));
assert.equal(advance(mine,[],1),mine);
mine = advance(mine,[],2);
assert.deepEqual(mine.stockByResource,{鉱石:1,宝石:1});
assert.equal(advance(mine,[],2),mine);
mine = advance(JSON.parse(JSON.stringify(mine)),[{hp:1}],3);
assert.equal(mine.suspended,true);
assert.deepEqual(mine.stockByResource,{鉱石:1,宝石:1});
mine = advance(mine,[{hp:0}],4);
assert.equal(mine.suspended,false);
assert.deepEqual(mine.stockByResource,{鉱石:2,宝石:2});
let slow = create(map,[],"p2",1,{...rules,productionBySiteKind:{ore:{resource:"鉄",amount:5}}});
slow = advance(slow,[],2,{...rules,productionIntervalTurns:2});
assert.deepEqual(slow.stockByResource,{});
slow = advance(slow,[],3,{...rules,productionIntervalTurns:2});
assert.deepEqual(slow.stockByResource,{鉄:5});
assert.deepEqual(advance(slow,[],30,{...rules,productionIntervalTurns:2}).stockByResource,{鉄:5});
assert.equal(advance(mine,[],NaN),mine);
console.log("cave mine: boss/residual enemies, ownership, resources, expiry-free stock, turn deduplication/save, pause/resume and overrides passed");
