import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {dirname,resolve as pathResolve} from 'node:path';
import {build} from 'esbuild';
const load=async path=>{
  const bundle=await build({entryPoints:[path],bundle:true,write:false,format:'esm',platform:'node',plugins:[{
    name:'native-sheet-registry-for-node',setup(builder){
      builder.onLoad({filter:/game-data-registry\.js$/},args=>{
        const directory=pathResolve('data/source/export/json');
        const modules=Object.fromEntries(readdirSync(directory).filter(name=>name.endsWith('.json')).map(name=>[`../../../data/source/export/json/${name}`,JSON.parse(readFileSync(`${directory}/${name}`,'utf8'))]));
        const contents=readFileSync(args.path,'utf8').replace(/import\.meta\.glob\([^;]+\);/,`${JSON.stringify(modules)};`);
        return {contents,loader:'js',resolveDir:dirname(args.path)};
      });
    }
  }]});
  return import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
};
const {resolveV39TerrainDisasterRules:resolve,V39_TERRAIN_DESTRUCTION_RULES:rules}=await load('frontend/src/lib/v39-terrain-disaster-rules.js');
const {damageV39Ground:damage,advanceV39GroundCollapses:advance,clearV39Rubble:clear}=await load('frontend/src/lib/v39-terrain-destruction.js');
